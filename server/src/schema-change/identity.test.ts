import { describe, expect, it } from "vitest";
import { compile, facts, MIB, plan, table } from "./test-fixtures.js";
import type { Runbook } from "./runbook.js";

const ledger = (overrides: Partial<Parameters<typeof table>[0]> = {}) =>
    table({ name: "ledger", rows: 5_000_000, bytes: 400 * MIB, columns: ["id:integer:notnull", "memo:text", "note:text"], indexes: [{ name: "ledger_id_idx", columns: ["id"] }], primaryKey: [], ...overrides });
const make = (changes: Record<string, unknown>, tables = [ledger()], options: Parameters<typeof compile>[2] = {}) => compile(plan({ type: "alter_column", tableName: "ledger", columnName: "id", changes: { autoIncrement: true, ...changes } }), facts(...tables), options);
const errors = (runbook: Runbook) => runbook.findings.filter((finding) => finding.severity === "error").map((finding) => finding.code);

describe("an existing column becoming an identity column", () => {
    it("adds the identity and starts its sequence after the largest value, in one transaction inside the lock retry", () => {
        const runbook = make({});
        expect(errors(runbook)).toEqual([]);
        expect(runbook.steps).toHaveLength(1);
        const step = runbook.steps[0];
        expect(step.title).toBe("Make public.ledger.id an identity column, starting after its largest value");
        expect(step.sql).toContain("DO $retry$");
        expect(step.sql).toContain("ALTER TABLE public.ledger ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;");
        expect(step.sql).toContain("PERFORM setval((SELECT d.objid FROM pg_depend d");
        expect(step.sql).toContain("d.deptype = 'i')::regclass, (SELECT COALESCE(max(id), 0) + 1 FROM public.ledger), false);");
        expect(step.sql).not.toContain("pg_get_serial_sequence");
        expect(step.undo).toBe("ALTER TABLE public.ledger ALTER COLUMN id DROP IDENTITY;");
        expect(step.notes.join(" ")).toMatch(/read through an index/);
    });

    it("is a DO block of its own when the retry is off", () => {
        const step = make({}, [ledger()], { settings: { lockAttempts: 1 } }).steps[0];
        expect(step.sql).toContain("DO $identity$");
        expect(step.sql).toContain("SET LOCAL lock_timeout = '2s';");
        expect(step.sql).not.toContain("$retry$");
    });

    it("needs an index on the column to find the largest value, unless the table is small", () => {
        expect(errors(make({}, [ledger({ indexes: [] })]))).toEqual(["index-needed"]);
        expect(errors(make({}, [ledger({ indexes: [{ name: "ledger_memo_idx", columns: ["memo", "id"] }] })]))).toEqual(["index-needed"]);
        expect(errors(make({}, [ledger({ rows: 100, bytes: 2 * MIB, indexes: [] })]))).toEqual([]);
        // an index added earlier in the same plan counts
        const both = compile(plan({ type: "add_index", tableName: "ledger", index: { name: "ledger_id_ix", columns: ["id"] } }, { type: "alter_column", tableName: "ledger", columnName: "id", changes: { autoIncrement: true } }), facts(ledger({ indexes: [] })));
        expect(errors(both)).toEqual([]);
    });

    it("needs the column NOT NULL, which the same change can do, and no default, which the same change can remove", () => {
        expect(errors(make({}, [ledger({ columns: ["id:integer", "memo:text"] })]))).toEqual(["not-null-required"]);
        const withNotNull = make({ nullable: false }, [ledger({ columns: ["id:integer", "memo:text"] })]);
        expect(errors(withNotNull)).toEqual([]);
        expect(withNotNull.steps.some((step) => step.title.includes("NOT NULL"))).toBe(true);
        expect(withNotNull.steps.at(-1)?.title).toContain("identity column");

        const serial = ledger();
        serial.columns[0].default = "nextval('ledger_id_seq'::regclass)";
        expect(errors(make({}, [serial]))).toEqual(["has-default"]);
        const serialToo = ledger();
        serialToo.columns[0].default = "nextval('ledger_id_seq'::regclass)";
        const converted = make({ defaultValue: null }, [serialToo]);
        expect(errors(converted)).toEqual([]);
        expect(converted.steps.map((step) => step.title)).toEqual(["Remove the default of public.ledger.id", "Make public.ledger.id an identity column, starting after its largest value"]);
    });

    it("refuses a column that is not an integer or is a generated column, and says when it already is one", () => {
        expect(errors(make({}, [ledger({ columns: ["id:text:notnull", "memo:text"] })]))).toEqual(["unsupported"]);
        const generated = ledger();
        generated.columns[0].generated = "stored";
        expect(errors(make({}, [generated]))).toEqual(["generated-column"]);
        const already = ledger();
        already.columns[0].generated = "always-identity";
        const runbook = make({}, [already]);
        expect(runbook.steps).toHaveLength(0);
        expect(runbook.findings.map((finding) => finding.code)).toContain("no-change");
    });

    it("detaches the sequence of an old serial default first on a server older than PostgreSQL 13, which cannot have both", () => {
        const old = facts(ledger());
        old.serverVersionNum = 120000;
        const step = compile(plan({ type: "alter_column", tableName: "ledger", columnName: "id", changes: { autoIncrement: true } }), old).steps[0];
        expect(step.sql).toContain("OWNED BY NONE");
        expect(step.sql.indexOf("OWNED BY NONE")).toBeLessThan(step.sql.indexOf("ADD GENERATED"));
        expect(step.notes.join(" ")).toMatch(/older than PostgreSQL 13/);
        expect(make({}).steps[0].sql).not.toContain("OWNED BY NONE");
    });
});
